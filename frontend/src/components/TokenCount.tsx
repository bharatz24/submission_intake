// Claude token indicators shared by the Monitoring page and the report screens: one icon + color per direction.
import InputIcon from '@mui/icons-material/Input';
import OutputIcon from '@mui/icons-material/Output';
import TollIcon from '@mui/icons-material/Toll';
import { Box, Chip, Tooltip } from '@mui/material';

import { formatTokens } from '../lib/status';
import type { Report } from '../types';

export type TokenKind = 'input' | 'output';
export const TOKEN_KIND = {
  input: {
    Icon: InputIcon,
    color: 'info.main',
    label: 'Input',
    hint: 'Input tokens: sent to Claude (skill instructions, prompt and evidence, including cached tokens)',
  },
  output: {
    Icon: OutputIcon,
    color: 'secondary.main',
    label: 'Output',
    hint: 'Output tokens: generated by Claude, including thinking',
  },
} as const;

/** Token count with its input/output indicator: compact in the cell, exact on hover. Table cells under a `TokenHeader` pass `icon={false}`. */
export function Tokens({
  n,
  kind,
  cached,
  icon = true,
}: {
  n: number;
  kind: TokenKind;
  cached?: number;
  icon?: boolean;
}) {
  const { Icon, color, label } = TOKEN_KIND[kind];
  const title = `${n.toLocaleString()} ${label.toLowerCase()} tokens${cached ? ` (${cached.toLocaleString()} from cache)` : ''}`;
  return (
    <Tooltip title={title}>
      <Box
        component="span"
        sx={{
          display: 'inline-flex',
          alignItems: 'center',
          gap: 0.5,
          fontVariantNumeric: 'tabular-nums',
          whiteSpace: 'nowrap',
        }}
      >
        {icon && <Icon sx={{ fontSize: '0.95rem', color }} />}
        {formatTokens(n)}
      </Box>
    </Tooltip>
  );
}

/** Column header naming the token direction, with its icon and an explanation on hover. Narrow tables can hide `.TokenHeader-label`. */
export function TokenHeader({ kind }: { kind: TokenKind }) {
  const { Icon, color, label, hint } = TOKEN_KIND[kind];
  return (
    <Tooltip title={hint}>
      <Box component="span" sx={{ display: 'inline-flex', alignItems: 'center', gap: 0.5, whiteSpace: 'nowrap' }}>
        <Icon sx={{ fontSize: '0.95rem', color }} />
        <span className="TokenHeader-label">{label}</span>
      </Box>
    </Tooltip>
  );
}

/** Chip for one Claude call's usage, e.g. on a report header: [token icon] (in) 12.3k (out) 2.1k. */
export function TokenUsageChip({ usage }: { usage: Report['usage'] }) {
  if (usage?.inputTokens == null || usage.outputTokens == null) return null;
  return (
    <Chip
      size="small"
      variant="outlined"
      icon={<TollIcon sx={{ fontSize: '0.95rem !important' }} />}
      label={
        <Box component="span" sx={{ display: 'inline-flex', alignItems: 'center', gap: 1 }}>
          <Tokens n={usage.inputTokens} kind="input" />
          <Tokens n={usage.outputTokens} kind="output" />
        </Box>
      }
    />
  );
}
