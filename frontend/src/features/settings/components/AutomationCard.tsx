import {
  Alert,
  Box,
  Button,
  Chip,
  List,
  ListItem,
  ListItemText,
  Stack,
  ToggleButton,
  ToggleButtonGroup,
  Typography,
} from '@mui/material';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useState } from 'react';

import { useAuth } from '../../../auth/AuthContext';
import { hasPermission } from '../../../auth/permissions';
import { ErrorState, Loading } from '../../../components/common';
import { useToast } from '../../../components/feedback/FeedbackProvider';
import { TOAST_MESSAGES } from '../../../constants';
import { useAutomation } from '../../../lib/automation';
import { api, apiWith, errorMessage } from '../../../services/api';
import type { AutomationMode, AutomationSettings, AutomationStep } from '../../../types';
import { settingsKeys } from '../queryKeys';
import { SettingsPanel } from './SettingsShell';

// The pipeline steps in the order they run. Auto: the step runs by itself when a new email arrives. Manual: it waits
// until someone clicks the step's button on the submission; a click always runs the step in full.
const AUTOMATION_STEPS: {
  key: AutomationStep;
  label: string;
  llm: boolean;
  auto: string;
  manual: string;
  needs?: AutomationStep;
}[] = [
  {
    key: 'classification',
    label: 'Email classification',
    llm: true,
    auto: 'When a new email arrives, Claude decides whether it is a submission (when the rules are not sure).',
    manual:
      'Claude is not asked. Emails the rules cannot decide go to Review required; an underwriter sets the classification.',
  },
  {
    key: 'fieldExtraction',
    label: 'Field extraction',
    llm: true,
    auto: 'When a new email arrives, Claude reads the email and attachments and fills in the applicant fields.',
    manual: 'Nothing is extracted on arrival. Click "Re-run extraction + NPI" on the submission to extract the fields.',
  },
  {
    key: 'npiVerification',
    label: 'NPI verification',
    llm: false,
    auto: 'When a new email arrives, every NPI found is checked against the NPI Registry.',
    manual: 'Not checked on arrival. Click "Re-verify" on the NPI tab (or "Re-run extraction + NPI").',
  },
  {
    key: 'synthesis',
    label: 'Synthesis report',
    llm: true,
    auto: 'Generated by itself as soon as a new submission is ready for review.',
    manual: 'Not generated on arrival. Click Generate on the Synthesis tab.',
  },
  {
    key: 'analysis',
    label: 'Underwriting analysis',
    llm: true,
    needs: 'synthesis',
    auto: 'Generated by itself right after the automatic Synthesis.',
    manual: 'Not generated on arrival. Click Generate on the Analysis tab.',
  },
  {
    key: 'autoQuote',
    label: 'Automatic quote',
    llm: true,
    needs: 'analysis',
    auto: 'A first quote is priced by itself right after the automatic Analysis.',
    manual: 'No quote on arrival. Underwriters create quotes on the Quotes tab.',
  },
];

/** Settings → Automation: one Auto / Manual choice per pipeline step. Changes apply to what runs from now on. */
export function AutomationCard() {
  const { user } = useAuth();
  const admin = hasPermission(user, 'settings:manage');
  const qc = useQueryClient();
  const settings = useAutomation();
  const anthropic = useQuery({
    queryKey: settingsKeys.anthropic(),
    queryFn: ({ signal }) => apiWith(signal).anthropicSettings(),
  });
  const noKey = anthropic.data ? !anthropic.data.keySet : false;
  const [draft, setDraft] = useState<Partial<AutomationSettings>>({});
  const toast = useToast();
  const save = useMutation({
    meta: { silentError: true }, // its error is shown where it happened, not as a toast
    mutationFn: api.saveAutomationSettings,
    onSuccess: (data) => {
      toast.success(TOAST_MESSAGES.automationSaved);
      qc.setQueryData(settingsKeys.automation(), data);
      setDraft({});
    },
  });
  const s = settings.data;
  const value = (k: AutomationStep): AutomationMode => draft[k] ?? s?.[k] ?? 'AUTO';
  const changes = s
    ? (Object.fromEntries(
        Object.entries(draft).filter(([k, v]) => v !== s[k as AutomationStep]),
      ) as Partial<AutomationSettings>)
    : {};
  const dirty = Object.keys(changes).length > 0;
  const setAll = (mode: AutomationMode) => {
    save.reset();
    setDraft(Object.fromEntries(AUTOMATION_STEPS.map((st) => [st.key, mode])));
  };
  const llmSteps = AUTOMATION_STEPS.filter((st) => st.llm);
  // The first earlier step this one waits on that is Manual (Analysis needs an automatic Synthesis, the quote an Analysis).
  const blockedBy = (k: AutomationStep): AutomationStep | null => {
    for (
      let need = AUTOMATION_STEPS.find((x) => x.key === k)?.needs;
      need;
      need = AUTOMATION_STEPS.find((x) => x.key === need)?.needs
    ) {
      if (value(need) === 'MANUAL') return need;
    }
    return null;
  };
  const llmOn = noKey ? 0 : llmSteps.filter((st) => value(st.key) === 'AUTO' && !blockedBy(st.key)).length;
  // Steps are chained (Synthesis → Analysis → quote), so one change carries along the chain: Manual also makes every
  // step that waits on this one Manual; Auto also makes every step this one waits on Auto.
  const setMode = (k: AutomationStep, mode: AutomationMode) => {
    const linked = new Set<AutomationStep>([k]);
    if (mode === 'MANUAL') {
      for (let grew = true; grew; ) {
        grew = false;
        for (const st of AUTOMATION_STEPS) {
          if (st.needs && linked.has(st.needs) && !linked.has(st.key)) {
            linked.add(st.key);
            grew = true;
          }
        }
      }
    } else {
      for (
        let need = AUTOMATION_STEPS.find((x) => x.key === k)?.needs;
        need;
        need = AUTOMATION_STEPS.find((x) => x.key === need)?.needs
      ) {
        linked.add(need);
      }
    }
    save.reset();
    setDraft((d) => ({ ...d, ...Object.fromEntries([...linked].map((step) => [step, mode])) }));
  };
  // The steps whose mode a change to this one also sets, for the hint under the row.
  const dependents = (k: AutomationStep) => AUTOMATION_STEPS.filter((x) => x.needs === k).map((x) => x.label);

  return (
    <SettingsPanel
      title="Automation"
      fullWidth
      subtitle="Auto: the step runs by itself when a new email arrives. Manual: it waits until someone clicks its button on the submission, and a click always runs it in full. Changes apply from now on; submissions already processed are not re-run."
    >
      {settings.isLoading ? (
        <Loading label="Loading settings…" shape="form" />
      ) : settings.isError ? (
        <ErrorState error={settings.error} onRetry={() => settings.refetch()} />
      ) : s ? (
        <Stack spacing={2}>
          <Stack direction="row" spacing={1} alignItems="center" flexWrap="wrap" useFlexGap>
            <Chip
              size="small"
              variant="outlined"
              color={llmOn ? 'primary' : 'default'}
              label={`${llmOn} of ${llmSteps.length} Claude steps automatic`}
            />
            <Box sx={{ flexGrow: 1 }} />
            {admin && (
              <>
                <Button size="small" disabled={save.isPending} onClick={() => setAll('AUTO')}>
                  All auto
                </Button>
                <Button size="small" disabled={save.isPending} onClick={() => setAll('MANUAL')}>
                  All manual
                </Button>
              </>
            )}
          </Stack>
          {noKey && (
            <Alert severity="warning" variant="outlined">
              No Claude API key is saved, so every Claude step behaves as Manual until one is added under Claude API.
            </Alert>
          )}
          <List dense disablePadding>
            {AUTOMATION_STEPS.map((st) => {
              const mode = value(st.key);
              const changed = mode !== s[st.key];
              return (
                <ListItem key={st.key} divider sx={{ px: 0, alignItems: 'flex-start', gap: 2 }}>
                  <ListItemText
                    primary={
                      <Stack direction="row" spacing={1} alignItems="center" flexWrap="wrap" useFlexGap>
                        <Typography variant="body2" fontWeight={600}>
                          {st.label}
                        </Typography>
                        <Chip
                          size="small"
                          variant="outlined"
                          label={st.llm ? 'Claude' : 'NPI Registry'}
                          sx={{ height: 20, fontSize: '0.7rem' }}
                        />
                        {changed && (
                          <Chip
                            size="small"
                            color="warning"
                            variant="outlined"
                            label="unsaved"
                            sx={{ height: 20, fontSize: '0.7rem' }}
                          />
                        )}
                      </Stack>
                    }
                    secondary={
                      <>
                        {mode === 'AUTO' ? st.auto : st.manual}
                        {mode === 'AUTO' && st.needs && blockedBy(st.key) && (
                          <Box component="span" sx={{ display: 'block', color: 'warning.main' }}>
                            Will not run by itself while{' '}
                            {AUTOMATION_STEPS.find((x) => x.key === blockedBy(st.key))!.label} is Manual.
                          </Box>
                        )}
                        {st.needs && (
                          <Box component="span" sx={{ display: 'block', fontStyle: 'italic' }}>
                            Needs {AUTOMATION_STEPS.find((x) => x.key === st.needs)!.label}: Auto here also sets it to
                            Auto.
                          </Box>
                        )}
                        {dependents(st.key).length > 0 && (
                          <Box component="span" sx={{ display: 'block', fontStyle: 'italic' }}>
                            Manual here also sets {dependents(st.key).join(', ')} to Manual.
                          </Box>
                        )}
                      </>
                    }
                    secondaryTypographyProps={{ component: 'div' }}
                  />
                  <ToggleButtonGroup
                    size="small"
                    exclusive
                    value={mode}
                    disabled={!admin || save.isPending}
                    sx={{ flexShrink: 0, mt: 0.5 }}
                    onChange={(_, v: AutomationMode | null) => {
                      if (v) setMode(st.key, v);
                    }}
                  >
                    <ToggleButton value="AUTO" sx={{ px: 1.5 }}>
                      Auto
                    </ToggleButton>
                    <ToggleButton value="MANUAL" sx={{ px: 1.5 }}>
                      Manual
                    </ToggleButton>
                  </ToggleButtonGroup>
                </ListItem>
              );
            })}
          </List>
          {admin ? (
            <Stack direction="row" spacing={1}>
              <Button variant="contained" disabled={!dirty || save.isPending} onClick={() => save.mutate(changes)}>
                {save.isPending ? 'Saving…' : 'Save'}
              </Button>
              <Button
                disabled={!dirty || save.isPending}
                onClick={() => {
                  save.reset();
                  setDraft({});
                }}
              >
                Discard
              </Button>
            </Stack>
          ) : (
            <Typography variant="caption" color="text.secondary">
              Only administrators can change automation.
            </Typography>
          )}
          {save.error && <Alert severity="error">{errorMessage(save.error)}</Alert>}
        </Stack>
      ) : null}
    </SettingsPanel>
  );
}
