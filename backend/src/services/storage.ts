export { StorageError } from './driveStorage.js';

/**
 * Attachment bytes always live in Google Drive (the Drive client, integrations/drive). documents.storage_backend is always 'GDRIVE';
 * the local-disk driver was removed.
 */

export type StorageBackend = 'GDRIVE';

/** The columns a read needs; every `SELECT * FROM documents` row satisfies it. */
export interface StoredDocument {
  id: string;
  storage_backend: string;
  storage_key: string;
  size_bytes?: number | string | null;
}

/** A file ready to store: IDs are generated by the caller so Drive metadata and DB rows agree from the start. */
export interface FileToStore {
  documentId: string;
  filename: string;
  mimeType: string;
  /** In memory, or a temporary file on disk (browser uploads); a disk file is streamed, never loaded whole. */
  data: FileBytes;
}

export interface PutFile {
  documentId: string;
  filename: string;
  mimeType: string;
  /** Type recognised from the file's bytes (fileType.ts); mimeType is only what the sender claimed. */
  detectedType: DetectedType;
  sizeBytes: number;
  sha256: string;
  storageBackend: StorageBackend;
  storageKey: string;
}

export const sha256Hex = (data: Buffer) => createHash('sha256').update(data).digest('hex');

/**
 * Store all files of one submission. All or nothing: when any upload fails the others are discarded and the
 * error is thrown, so the caller never records a submission with a missing document.
 */
export async function putDocumentFiles(
  submissionId: string,
  folder: { label: string; receivedAt: Date },
  files: FileToStore[],
): Promise<{ folderId: string | null; files: PutFile[] }> {
  if (!files.length) return { folderId: null, files: [] };
  const folderId = await integrations().drive.ensureSubmissionFolder(submissionId, folder.label, folder.receivedAt);
  const stored: PutFile[] = [];
  const failures: unknown[] = [];
  await mapLimit(files, config.GDRIVE_UPLOAD_CONCURRENCY, async (f) => {
    if (failures.length) return;
    try {
      const sha256 = await sha256Bytes(f.data);
      const storageKey = await integrations().drive.upload(folderId, {
        submissionId,
        documentId: f.documentId,
        filename: f.filename,
        mimeType: f.mimeType,
        sha256,
        data: f.data,
      });
      stored.push({
        documentId: f.documentId,
        filename: f.filename,
        mimeType: f.mimeType,
        detectedType: await sniffBytes(f.data),
        sizeBytes: byteLength(f.data),
        sha256,
        storageBackend: 'GDRIVE',
        storageKey,
      });
    } catch (err) {
      failures.push(err);
    }
  });
  if (failures.length) {
    await discardStoredFiles(stored);
    throw failures[0];
  }
  // Processing reads these next (text extraction, OCR): keep them in memory so Drive is not asked again. A disk file is
  // cached only when small; a large upload is read back from Drive by the extraction job instead of held here.
  for (const f of files) {
    if (Buffer.isBuffer(f.data)) fileCache.put(f.documentId, f.data);
    else if (f.data.size <= DOWNLOAD_BUFFER_MAX_BYTES) fileCache.put(f.documentId, await readAllBytes(f.data));
  }
  return { folderId, files: stored };
}

/** Bytes fileType.ts needs to recognise any type but a zip, whose central directory is at the end of the file. */
const SNIFF_HEAD_BYTES = 8192;

/** The detected type of a file in memory or on disk; a disk file is read whole only when it is a zip (docx, xlsx). */
async function sniffBytes(data: FileBytes): Promise<DetectedType> {
  if (Buffer.isBuffer(data)) return sniffFileType(data);
  const head = await readRange(data, 0, SNIFF_HEAD_BYTES);
  const isZip = head[0] === 0x50 && head[1] === 0x4b;
  return sniffFileType(isZip ? await readAllBytes(data) : head);
}

/** Trash one stored file; unlike discardStoredFiles, a Drive failure is thrown so the caller can retry it later. */
export async function trashStoredFile(f: Pick<PutFile, 'documentId' | 'storageKey'>): Promise<void> {
  fileCache.remove(f.documentId);
  await integrations().drive.trash(f.storageKey);
}

/** Best-effort removal of files whose DB rows were never committed; the orphan sweep catches anything left. */
export async function discardStoredFiles(
  files: Pick<PutFile, 'documentId' | 'storageBackend' | 'storageKey'>[],
): Promise<void> {
  for (const f of files) {
    fileCache.remove(f.documentId);
    try {
      await integrations().drive.trash(f.storageKey);
    } catch (err) {
      logger.warn({ err, documentId: f.documentId }, 'could not discard stored file');
    }
  }
}

/**
 * Open a document's bytes for sending to a browser: from the cache, else from Drive.
 * Resolves only once the source is readable (Drive answered), so callers can still answer 404/502 before sending
 * headers. Small files are read whole and cached, so a re-open is served from memory. Larger ones
 * (over DOWNLOAD_BUFFER_MAX_BYTES) are streamed through without being held in memory; if Drive drops one mid-way,
 * the connection is cut and the browser reports a failed download.
 */
export async function openStoredFile(doc: StoredDocument): Promise<Readable> {
  const cached = fileCache.get(doc.id);
  if (cached) return Readable.from([cached]);
  if (Number(doc.size_bytes ?? 0) <= DOWNLOAD_BUFFER_MAX_BYTES) return Readable.from([await readStoredFile(doc)]);
  if (doc.storage_backend !== 'GDRIVE')
    throw new StorageError('NOT_FOUND', `${doc.id} was stored on local disk, which is no longer supported`);
  return integrations().drive.download(doc.storage_key);
}

/** The whole file in memory (text extraction, Drive views). Fills the cache. */
export async function readStoredFile(doc: StoredDocument): Promise<Buffer> {
  const cached = fileCache.get(doc.id);
  if (cached) return cached;
  if (doc.storage_backend !== 'GDRIVE')
    throw new StorageError('NOT_FOUND', `${doc.id} was stored on local disk, which is no longer supported`);
  const source = await integrations().drive.download(doc.storage_key);
  const chunks: Buffer[] = [];
  try {
    for await (const chunk of source) chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
  } catch (err) {
    throw err instanceof StorageError
      ? err
      : new StorageError('UNAVAILABLE', `Reading ${doc.id} failed`, { cause: err });
  }
  const data = Buffer.concat(chunks);
  fileCache.put(doc.id, data);
  return data;
}

async function mapLimit<T>(items: T[], limit: number, fn: (item: T) => Promise<void>): Promise<void> {
  let next = 0;
  const worker = async () => {
    while (next < items.length) await fn(items[next++]!);
  };
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
}

// Types a browser can render inline without running content. HTML/SVG are deliberately absent (script execution).
const PREVIEW_TYPES: Record<string, string> = {
  pdf: 'application/pdf',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  gif: 'image/gif',
  webp: 'image/webp',
  bmp: 'image/bmp',
  txt: 'text/plain; charset=utf-8',
  csv: 'text/plain; charset=utf-8',
};

/**
 * Content type to serve a stored file inline, or null when it must only be downloaded.
 * Mail clients often send PDFs as application/octet-stream, so the extension decides when the MIME type is generic.
 */
export function previewMimeType(filename: string, mimeType: string, detected?: string | null): string | null {
  const declared = declaredPreviewType(filename, mimeType);
  // Files stored before content sniffing have no detected type: the declared type alone decides, as before.
  if (!detected) return declared;
  // A PDF or picture recognised from its bytes is shown as what it is, whatever it was labelled.
  const byContent = CONTENT_PREVIEW_TYPES[detected];
  if (byContent) return byContent;
  // Text is shown only when it was also declared as text (an .html file is text too, but is only downloaded).
  return detected === DETECTED.text && declared?.startsWith('text/plain') ? declared : null;
}

const CONTENT_PREVIEW_TYPES: Record<string, string> = {
  [DETECTED.pdf]: 'application/pdf',
  [DETECTED.png]: 'image/png',
  [DETECTED.jpeg]: 'image/jpeg',
  [DETECTED.gif]: 'image/gif',
  [DETECTED.webp]: 'image/webp',
  [DETECTED.bmp]: 'image/bmp',
};

function declaredPreviewType(filename: string, mimeType: string): string | null {
  const mime = mimeType.toLowerCase().split(';')[0]!.trim();
  const byMime = Object.values(PREVIEW_TYPES).find((t) => t.split(';')[0] === mime);
  if (byMime) return byMime;
  if (mime === 'text/csv') return PREVIEW_TYPES.csv!;
  if (mime && mime !== 'application/octet-stream' && mime !== 'binary/octet-stream') return null;
  const ext = path.extname(filename).slice(1).toLowerCase();
  return PREVIEW_TYPES[ext] ?? null;
}

export function safeFilename(name: string): string {
  return (
    path
      .basename(name)
      .replace(/[^\w.\- ()]/g, '_')
      .slice(0, 200) || 'attachment'
  );
}
